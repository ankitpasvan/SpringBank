'use client'

import { useCallback, useEffect, useState } from 'react'
import Link from 'next/link'
import { CreditCard, Plus } from 'lucide-react'
import { useToast } from '@/context/ToastContext.jsx'
import { createAccount, listAccounts } from '@/services/accountService.js'
import { getErrorMessage } from '@/lib/api'
import { formatAmount, formatDate } from '@/utils/format'
import Card from '@/components/common/Card.jsx'
import Button from '@/components/common/Button.jsx'
import Spinner from '@/components/common/Spinner.jsx'
import Alert from '@/components/common/Alert.jsx'
import EmptyState from '@/components/common/EmptyState.jsx'

export default function AccountsPage() {
    const toast = useToast()
    const [accounts, setAccounts] = useState([])
    const [loading, setLoading] = useState(true)
    const [error, setError] = useState('')
    const [accountType, setAccountType] = useState('SAVINGS')
    const [creating, setCreating] = useState(false)

    const load = useCallback(async () => {
        setLoading(true)
        setError('')
        try {
            setAccounts(await listAccounts())
        } catch (err) {
            setError(getErrorMessage(err))
        } finally {
            setLoading(false)
        }
    }, [])

    useEffect(() => {
        load()
    }, [load])

    const handleCreate = async (e) => {
        e.preventDefault()
        setCreating(true)
        try {
            const created = await createAccount(accountType)
            toast.success(`Account created — number ${created.accountNumber}.`)
            await load()
        } catch (err) {
            toast.error(getErrorMessage(err))
        } finally {
            setCreating(false)
        }
    }

    if (loading) return <Spinner label="Loading your accounts…" />

    return (
        <div className="space-y-6">
            <div>
                <h1 className="text-2xl font-extrabold tracking-tight sm:text-3xl">My Accounts</h1>
                <p className="mt-1 text-slate-600">All accounts you own. Select one to see details, deposit or withdraw.</p>
            </div>

            {error && <Alert type="error">{error}</Alert>}

            {/* Create account */}
            <Card className="p-5 sm:p-6">
                <h2 className="text-lg font-bold">Open a new account</h2>
                <p className="mt-0.5 text-sm text-slate-500">
                    Choose an account type. Your account number is generated by the bank and your balance starts at 0.00.
                </p>
                <form onSubmit={handleCreate} className="mt-4 flex flex-col gap-3 sm:flex-row sm:items-end">
                    <div className="w-full sm:max-w-xs">
                        <label htmlFor="account-type" className="mb-1.5 block text-sm font-semibold text-ink">
                            Account type
                        </label>
                        <select
                            id="account-type"
                            value={accountType}
                            onChange={(e) => setAccountType(e.target.value)}
                            className="w-full rounded-xl border border-slate-300 bg-white px-4 py-2.5 text-[15px] focus:border-brand-600 focus:outline-none focus:ring-2 focus:ring-brand-600/20"
                        >
                            <option value="SAVINGS">Savings Account</option>
                            <option value="CURRENT">Current Account</option>
                        </select>
                    </div>
                    <Button type="submit" loading={creating} size="md">
                        <Plus className="h-4 w-4" aria-hidden="true" />
                        Open account
                    </Button>
                </form>
            </Card>

            {accounts.length === 0 ? (
                <Card>
                    <EmptyState
                        icon={CreditCard}
                        title="No accounts yet"
                        description="You have not opened an account yet. Use the form above to open your first Savings or Current account."
                    />
                </Card>
            ) : (
                <div className="grid gap-4 sm:grid-cols-2">
                    {accounts.map((a) => (
                        <Link key={a.id} href={`/accounts/${a.id}`} className="group">
                            <Card className="h-full p-5 transition group-hover:shadow-lift sm:p-6">
                                <div className="flex items-start justify-between gap-3">
                  <span className="flex h-11 w-11 items-center justify-center rounded-xl bg-brand-50 text-brand-600">
                    <CreditCard className="h-5 w-5" aria-hidden="true" />
                  </span>
                                    <span className="rounded-full bg-slate-100 px-3 py-1 text-xs font-bold text-slate-600">
                    {a.accountType}
                  </span>
                                </div>
                                <p className="mt-4 text-sm font-medium text-slate-500">Account number</p>
                                <p className="mt-0.5 font-mono text-lg font-bold tracking-wide text-ink">{a.accountNumber}</p>
                                <p className="mt-4 text-sm font-medium text-slate-500">Balance</p>
                                <p className="mt-0.5 text-2xl font-extrabold tracking-tight text-ink">{formatAmount(a.balance)}</p>
                                <p className="mt-3 text-xs text-slate-400">Opened {formatDate(a.createdAt)}</p>
                                <p className="mt-4 text-sm font-semibold text-brand-700 group-hover:underline">
                                    View details →
                                </p>
                            </Card>
                        </Link>
                    ))}
                </div>
            )}
        </div>
    )
}
